import 'dart:convert';

import 'package:flutter/services.dart';
import 'package:image/image.dart' as image;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../api.dart';

/// Builds customer-facing documents only from the deliberately safe receipt API.
/// Purchase cost/profit, internal notes and customer ID proofs are never accepted
/// by this layout, so they cannot accidentally leak into a sale invoice.
class ReceiptDocument {
  static const _indigo = PdfColor.fromInt(0xff4f46e5);
  static const _mint = PdfColor.fromInt(0xff0f9f7a);
  static const _ink = PdfColor.fromInt(0xff172033);
  static const _muted = PdfColor.fromInt(0xff667085);
  static const _line = PdfColor.fromInt(0xffe4e7ec);
  static const _soft = PdfColor.fromInt(0xfff5f7ff);
  static const _successSoft = PdfColor.fromInt(0xffecfdf3);
  static const _warningSoft = PdfColor.fromInt(0xfffffaeb);

  static Future<Uint8List> build(Map<String, dynamic> receipt) async {
    final regular = pw.Font.ttf(await rootBundle.load('assets/fonts/Manrope-Regular.ttf'));
    final medium = pw.Font.ttf(await rootBundle.load('assets/fonts/Manrope-Medium.ttf'));
    final bold = pw.Font.ttf(await rootBundle.load('assets/fonts/Manrope-Bold.ttf'));
    final isSale = receipt['type'] == 'sale';
    final shop = _map(receipt['shop']);
    final customer = _map(receipt['customer']);
    final phone = _map(receipt['phone']);
    final logo = _image(shop['logo_data']);
    final title = isSale ? 'SALE INVOICE' : 'PURCHASE RECEIPT';
    final partyTitle = isSale ? 'BILL TO' : 'PURCHASED FROM';
    final amountTitle = isSale ? 'Invoice total' : 'Purchase amount';
    final document = pw.Document(
      theme: pw.ThemeData.withFont(base: regular, bold: bold, italic: medium),
    );

    document.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(34, 32, 34, 30),
      footer: (context) => pw.Container(
        padding: const pw.EdgeInsets.only(top: 10),
        decoration: const pw.BoxDecoration(border: pw.Border(top: pw.BorderSide(color: _line, width: .7))),
        child: pw.Row(mainAxisAlignment: pw.MainAxisAlignment.spaceBetween, children: [
          pw.Text('Digitally generated by Vktrix Mobile', style: const pw.TextStyle(fontSize: 8.5, color: _muted)),
          pw.Text('Page ${context.pageNumber} of ${context.pagesCount}', style: const pw.TextStyle(fontSize: 8.5, color: _muted)),
        ]),
      ),
      build: (context) => [
        pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
          _logo(logo, shop['name']),
          pw.SizedBox(width: 14),
          pw.Expanded(child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
            pw.Text(_text(shop['name'], fallback: 'Mobile Shop'),
              style: pw.TextStyle(font: bold, fontSize: 19, color: _ink)),
            if (_has(shop['owner_name'])) pw.Text('Owner: ${_text(shop['owner_name'])}', style: const pw.TextStyle(fontSize: 9.5, color: _muted)),
            if (_has(shop['address'])) pw.Padding(padding: const pw.EdgeInsets.only(top: 3),
              child: pw.Text(_text(shop['address']), style: const pw.TextStyle(fontSize: 9.5, color: _muted))),
            pw.Wrap(spacing: 10, runSpacing: 2, children: [
              if (_has(shop['phone'])) pw.Text('Phone: ${_text(shop['phone'])}', style: const pw.TextStyle(fontSize: 9.5, color: _muted)),
              if (_has(shop['gst_no'])) pw.Text('GSTIN: ${_text(shop['gst_no'])}', style: const pw.TextStyle(fontSize: 9.5, color: _muted)),
            ]),
          ])),
          pw.SizedBox(width: 16),
          pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.end, children: [
            pw.Container(
              padding: const pw.EdgeInsets.symmetric(horizontal: 11, vertical: 6),
              decoration: pw.BoxDecoration(color: _soft, borderRadius: pw.BorderRadius.circular(5)),
              child: pw.Text(title, style: pw.TextStyle(font: bold, fontSize: 10, color: _indigo, letterSpacing: .7)),
            ),
            pw.SizedBox(height: 8),
            pw.Text(_text(receipt['number']), style: pw.TextStyle(font: bold, fontSize: 11, color: _ink)),
            pw.Text(_prettyDate(receipt['date']), style: const pw.TextStyle(fontSize: 9.5, color: _muted)),
          ]),
        ]),
        pw.SizedBox(height: 22),
        pw.Container(height: 3, decoration: pw.BoxDecoration(
          borderRadius: pw.BorderRadius.circular(2),
          gradient: const pw.LinearGradient(colors: [_indigo, _mint]),
        )),
        pw.SizedBox(height: 18),
        pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
          pw.Expanded(child: _partyCard(partyTitle, customer)),
          pw.SizedBox(width: 12),
          pw.Expanded(child: _summaryCard(receipt, isSale)),
        ]),
        pw.SizedBox(height: 20),
        _sectionTitle('DEVICE DETAILS'),
        pw.SizedBox(height: 8),
        _deviceTable(phone),
        pw.SizedBox(height: 18),
        pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
          pw.Expanded(flex: 5, child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
            _sectionTitle(isSale ? 'WARRANTY' : 'ACKNOWLEDGEMENT'),
            pw.SizedBox(height: 8),
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.all(12),
              decoration: pw.BoxDecoration(color: _soft, borderRadius: pw.BorderRadius.circular(7),
                border: pw.Border.all(color: _line, width: .7)),
              child: pw.Text(
                isSale
                  ? _text(receipt['warranty'], fallback: 'No shop warranty mentioned on this invoice.')
                  : 'Phone received for the amount shown. Device identifiers and customer details above were recorded at purchase.',
                style: const pw.TextStyle(fontSize: 9.5, color: _ink, lineSpacing: 2)),
            ),
          ])),
          pw.SizedBox(width: 16),
          pw.Expanded(flex: 4, child: pw.Container(
            padding: const pw.EdgeInsets.all(14),
            decoration: pw.BoxDecoration(color: _ink, borderRadius: pw.BorderRadius.circular(8)),
            child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.stretch, children: [
              pw.Text(amountTitle, style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey300)),
              pw.SizedBox(height: 4),
              pw.Text(rs(receipt['amount']), textAlign: pw.TextAlign.right,
                style: pw.TextStyle(font: bold, fontSize: 20, color: PdfColors.white)),
              if (isSale) ...[
                pw.SizedBox(height: 10),
                pw.Divider(color: PdfColors.grey700, height: 1),
                pw.SizedBox(height: 8),
                _amountRow('Received', receipt['paid_amount'], PdfColors.white),
                pw.SizedBox(height: 4),
                _amountRow('Balance due', receipt['balance_due'],
                  (num.tryParse('${receipt['balance_due']}') ?? 0) > 0 ? PdfColors.amber200 : PdfColors.green200),
              ],
            ]),
          )),
        ]),
        pw.SizedBox(height: 28),
        pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.end, children: [
          pw.Expanded(child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
            pw.Text('Important', style: pw.TextStyle(font: bold, fontSize: 9.5, color: _ink)),
            pw.SizedBox(height: 3),
            pw.Text('Please keep this PDF for your records. Verify the IMEI on the device with the number printed above.',
              style: const pw.TextStyle(fontSize: 8.5, color: _muted, lineSpacing: 2)),
          ])),
          pw.SizedBox(width: 30),
          pw.Container(width: 155, padding: const pw.EdgeInsets.only(top: 28),
            decoration: const pw.BoxDecoration(border: pw.Border(bottom: pw.BorderSide(color: _ink, width: .8))),
            child: pw.Text('Authorised signature', textAlign: pw.TextAlign.center,
              style: const pw.TextStyle(fontSize: 8, color: _muted))),
        ]),
      ],
    ));
    return document.save();
  }

  static pw.Widget _logo(pw.MemoryImage? image, dynamic shopName) {
    if (image != null) {
      // Server logo ko square tile bana kar rakhta hai (margin trim + centre),
      // isliye bill par bhi wahi "set" logo aata hai — chhota floating nahi.
      return pw.Container(width: 58, height: 58, padding: const pw.EdgeInsets.all(2),
        decoration: pw.BoxDecoration(borderRadius: pw.BorderRadius.circular(14), border: pw.Border.all(color: _line)),
        child: pw.Image(image, fit: pw.BoxFit.cover));
    }
    // `substring(0, 1)` emoji (surrogate pair) shop name ko tod deta tha; runes
    // poora code point dete hain.
    final name = _text(shopName, fallback: 'V').trim();
    final initial = name.isEmpty ? 'V' : String.fromCharCode(name.runes.first).toUpperCase();
    return pw.Container(width: 58, height: 58,
      decoration: pw.BoxDecoration(color: _indigo, borderRadius: pw.BorderRadius.circular(12)),
      alignment: pw.Alignment.center,
      child: pw.Text(initial, style: pw.TextStyle(fontSize: 25, fontWeight: pw.FontWeight.bold, color: PdfColors.white)));
  }

  static pw.Widget _partyCard(String title, Map<String, dynamic> customer) => pw.Container(
    padding: const pw.EdgeInsets.all(12),
    decoration: pw.BoxDecoration(borderRadius: pw.BorderRadius.circular(7), border: pw.Border.all(color: _line, width: .7)),
    child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
      _sectionTitle(title),
      pw.SizedBox(height: 7),
      pw.Text(_text(customer['name'], fallback: 'Walk-in customer'),
        style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 10.5, color: _ink)),
      if (_has(customer['phone'])) pw.Padding(padding: const pw.EdgeInsets.only(top: 3),
        child: pw.Text('Phone: ${_text(customer['phone'])}', style: const pw.TextStyle(fontSize: 9, color: _muted))),
      if (_has(customer['address'])) pw.Padding(padding: const pw.EdgeInsets.only(top: 3),
        child: pw.Text(_text(customer['address']), style: const pw.TextStyle(fontSize: 9, color: _muted), maxLines: 3)),
    ]),
  );

  static pw.Widget _summaryCard(Map<String, dynamic> receipt, bool isSale) {
    final due = num.tryParse('${receipt['balance_due']}') ?? 0;
    final status = !isSale ? 'PURCHASED' : due <= 0 ? 'PAID' : (num.tryParse('${receipt['paid_amount']}') ?? 0) > 0 ? 'PART PAYMENT' : 'PAYMENT DUE';
    final background = !isSale || due <= 0 ? _successSoft : _warningSoft;
    final color = !isSale || due <= 0 ? _mint : PdfColors.orange800;
    return pw.Container(
      padding: const pw.EdgeInsets.all(12),
      decoration: pw.BoxDecoration(color: background, borderRadius: pw.BorderRadius.circular(7)),
      child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
        pw.Text(status, style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9, color: color, letterSpacing: .5)),
        pw.SizedBox(height: 7),
        _keyValue('Document no.', receipt['number']),
        pw.SizedBox(height: 4),
        _keyValue('Date', _prettyDate(receipt['date'])),
        if (isSale) ...[
          pw.SizedBox(height: 4),
          _keyValue('Payment', _text(receipt['payment_mode'], fallback: 'cash').toUpperCase()),
        ],
      ]),
    );
  }

  static pw.Widget _keyValue(String key, dynamic value) => pw.Row(children: [
    pw.Expanded(child: pw.Text(key, style: const pw.TextStyle(fontSize: 8.5, color: _muted))),
    pw.SizedBox(width: 8),
    pw.Text(_text(value), style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 8.5, color: _ink)),
  ]);

  static pw.Widget _deviceTable(Map<String, dynamic> phone) {
    final rows = <(String, String)>[
      ('Device', [phone['brand'], phone['model']].map((e) => _text(e)).where((e) => e.isNotEmpty).join(' ')),
      ('IMEI 1', _text(phone['imei'])),
      if (_has(phone['imei2'])) ('IMEI 2', _text(phone['imei2'])),
      if (_has(phone['serial_number'])) ('Serial number', _text(phone['serial_number'])),
      ('Variant', [phone['ram'], phone['storage'], phone['color']].map((e) => _text(e)).where((e) => e.isNotEmpty).join(' · ')),
      if (_has(phone['condition'])) ('Condition', _text(phone['condition'])),
      if (_has(phone['accessories'])) ('Accessories', _text(phone['accessories'])),
    ];
    return pw.Table(
      border: pw.TableBorder.all(color: _line, width: .7),
      columnWidths: const {0: pw.FlexColumnWidth(1.35), 1: pw.FlexColumnWidth(3.65)},
      children: [
        for (var i = 0; i < rows.length; i++) pw.TableRow(
          decoration: pw.BoxDecoration(color: i.isEven ? PdfColors.white : _soft),
          children: [
            pw.Padding(padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
              child: pw.Text(rows[i].$1, style: const pw.TextStyle(fontSize: 9, color: _muted))),
            pw.Padding(padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
              child: pw.Text(rows[i].$2.isEmpty ? '—' : rows[i].$2,
                style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 9.5, color: _ink))),
          ],
        ),
      ],
    );
  }

  static pw.Widget _sectionTitle(String value) => pw.Text(value,
    style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 8.5, color: _indigo, letterSpacing: .7));

  static pw.Widget _amountRow(String label, dynamic value, PdfColor color) => pw.Row(children: [
    pw.Expanded(child: pw.Text(label, style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey300))),
    pw.Text(rs(value), style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 10, color: color)),
  ]);

  static Map<String, dynamic> _map(dynamic value) => value is Map ? Map<String, dynamic>.from(value) : <String, dynamic>{};
  static bool _has(dynamic value) => value != null && '$value'.trim().isNotEmpty && '$value' != 'null';
  static String _text(dynamic value, {String fallback = ''}) => _has(value) ? '$value'.trim() : fallback;

  static String _prettyDate(dynamic value) {
    final raw = _text(value);
    final date = DateTime.tryParse(raw.length >= 10 ? raw.substring(0, 10) : raw);
    if (date == null) return raw;
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    return '${date.day.toString().padLeft(2, '0')} ${months[date.month - 1]} ${date.year}';
  }

  static pw.MemoryImage? _image(dynamic dataUrl) {
    try {
      final raw = _text(dataUrl);
      final comma = raw.indexOf(',');
      if (comma < 0 || !raw.startsWith('data:image/')) return null;
      final bytes = base64Decode(raw.substring(comma + 1));
      // MemoryImage decodes lazily while painting the page. Validate here so a
      // corrupt/legacy logo falls back to the shop initial instead of breaking
      // the entire receipt generation.
      if (image.decodeImage(bytes) == null) return null;
      return pw.MemoryImage(bytes);
    } catch (_) {
      return null;
    }
  }
}
